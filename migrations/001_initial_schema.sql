CREATE TABLE IF NOT EXISTS "trainer_buildings" (
	"id" INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY,
	"trainer_id" INTEGER NOT NULL,
	"building_id" INTEGER NOT NULL,
	"status" TRAINER_BUILDING_STATUS NOT NULL DEFAULT 'pending',
	"reviewed_by" INTEGER,
	"reason" TEXT,
